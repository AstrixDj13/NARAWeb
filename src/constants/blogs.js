// Responsive srcSet for a blog image. Shopify CDN images are resized via the `width` param;
// local /public images use the pre-generated "-400.webp" variant.
export const blogImageSrcSet = (src) => {
    if (src.includes("cdn.shopify.com")) {
        const sep = src.includes("?") ? "&" : "?";
        return `${src}${sep}width=400 400w, ${src}${sep}width=800 800w, ${src} 1200w`;
    }
    return `${src.replace(".webp", "-400.webp")} 400w, ${src} 1200w`;
};
